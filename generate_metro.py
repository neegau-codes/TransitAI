TRAVEL_TIME_PER_STATION = 1.5

def get_frequency(h, m):
    if h == 6: return 15
    if h == 7: return 10
    if h == 20: return 10
    if h == 21 or (h == 22 and m <= 30): return 15
    return 7

schedules = []
curr_time = 6 * 60
end_time = 22 * 60 + 30

while curr_time <= end_time:
    h = curr_time // 60
    m = curr_time % 60
    schedules.append(f"{h:02d}:{m:02d}")
    freq = get_frequency(h, m)
    curr_time += freq

connections = []

for i in range(len(STATIONS)):
    for j in range(len(STATIONS)):
        if i == j: continue
        
        dist = abs(i - j)
        duration = int(dist * TRAVEL_TIME_PER_STATION)
        cost = FARE_MATRIX[i][j]
        
        # We assume 1 km per station approx for distance
        distance_km = float(dist)
        
        connections.append({
            "source": STATIONS[i],
            "destination": STATIONS[j],
            "duration": duration,
            "cost": cost,
            "distance_km": distance_km,
            "schedules": schedules
        })

metro_routes = [
    {
        "provider": "Kochi Metro",
        "route_name": "Kochi Metro Line 1",
        "connections": connections
    }
]

with open("ingestion/data/metro_routes.json", "w") as f:
    json.dump(metro_routes, f, indent=2)

